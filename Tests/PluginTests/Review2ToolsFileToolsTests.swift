import AFMKernel
import Foundation
import LocalFileSystemPlugin
import TestSupport
import Testing

@testable import FileToolsPlugin

/// Review round 2: checksum files that must not be misread, Decode that must say what is
/// missing, and the tools that must never touch what was there before.
@Suite struct Review2FileTools {
    let box: Sandbox
    let registry = FileSystemRegistry()

    init() throws {
        box = try Sandbox()
        registry.register(LocalFileSystem())
    }

    func item(_ path: String) throws -> FileItem {
        try #require(registry.item(at: box.url(path)))
    }

    func run(
        asking answer: ExistingFileChoice = .overwrite, cancel: CancellationFlag = CancellationFlag(),
        cancelOnAsk: Int? = nil
    ) -> ToolRun {
        // Used by the callbacks, which run one at a time while the calls below wait for them.
        nonisolated(unsafe) var asked = 0
        return ToolRun(
            fileSystems: registry, cancellation: cancel, report: { _ in },
            askExisting: { _ in
                asked += 1
                if asked == cancelOnAsk { cancel.cancel() }
                return answer
            })
    }

    func names(_ folder: String) -> [String] {
        ((try? FileManager.default.contentsOfDirectory(atPath: box.url(folder).path)) ?? []).sorted()
    }

    // MARK: Checksum files

    @Test func sfvNamesThatLookLikeCommentsAreEntries() {
        let text =
            "; Generated by WIN-SFV32 v1.1a on 12/10/2005 at 09:07.46\n#notes.txt 1A2B3C4D\n;x.txt 00000001\nok.txt 0000000F\n"
        let entries = ChecksumFile.parse(text, fileName: "set.sfv")
        #expect(entries.map(\.name) == ["#notes.txt", ";x.txt", "ok.txt"])
        // Written so that it reads back as itself.
        let line = ChecksumFile.line(name: ";x.txt", digest: [0, 0, 0, 1], method: .crc32)
        #expect(line == "./;x.txt 00000001")
        #expect(ChecksumFile.parse(line, fileName: "set.sfv").map(\.name) == ["./;x.txt"])
        // In the other formats a line that starts with # or ; is a comment.
        #expect(ChecksumFile.parse("# a comment 1A2B3C4D\n", fileName: "set.md5").isEmpty)
    }

    @Test func linesThatCannotBeReadAreCounted() {
        let text =
            "d41d8cd98f00b204e9800998ecf8427 *short.txt\n\nd41d8cd98f00b204e9800998ecf8427e *\nd41d8cd98f00b204e9800998ecf8427e *fine.txt\njunk\n"
        let parsed = ChecksumFile.parseLines(text, fileName: "x.md5")
        #expect(parsed.entries.map(\.name) == ["fine.txt"])
        #expect(parsed.unreadableLines == [1, 3, 5])
        #expect(ChecksumFile.parseLines("", fileName: "x.md5").unreadableLines.isEmpty)
    }

    @Test func emptyAndUnreadableChecksumFilesAreErrors() throws {
        try box.file("empty.md5", "")
        try box.file("junk.sha256", "this is prose, not checksums\nsecond line\n")
        try box.file("short.md5", "d41d8cd98f00b204e9800998ecf8427 *a.txt\n")
        try box.file("a.txt", "alpha")
        let files = try ["empty.md5", "junk.sha256", "short.md5"].map(item)
        let report = try ChecksumRun.verify(checksumFiles: files, run: run())
        #expect(report.errors == 1 + 2 + 1)
        #expect(report.count(.unreadable) == 4 && report.count(.ok) == 0)
        #expect(report.text(onlyErrors: true).contains("Cannot read any checksum"))
        #expect(report.text(onlyErrors: true).contains("Cannot read line 2!"))
        #expect(report.failedNames.contains("empty.md5"))
    }

    @Test func sfvEntriesWithCommentLikeNamesAreVerified() throws {
        try box.file("#notes.txt", "one")
        try box.file(";x.txt", "two")
        try box.file("ok.txt", "three")
        let entries = try ["#notes.txt", ";x.txt", "ok.txt"].map { name -> (name: String, digest: [UInt8]) in
            let hasher = CRC32Hasher()
            hasher.update(try Data(contentsOf: box.url(name)))
            return (name, hasher.finish())
        }
        let data = ChecksumFile.contents(entries, method: .crc32, unixFormat: true, byteOrderMark: false)
        try data.write(to: box.url("set.sfv"))
        #expect(try ChecksumRun.verify(checksumFiles: [item("set.sfv")], run: run()).count(.ok) == 3)
        // Damaged, both are caught.
        try "changed".write(to: box.url("#notes.txt"), atomically: true, encoding: .utf8)
        try "changed".write(to: box.url(";x.txt"), atomically: true, encoding: .utf8)
        let report = try ChecksumRun.verify(checksumFiles: [item("set.sfv")], run: run())
        #expect(report.count(.wrongChecksum) == 2 && report.count(.ok) == 1 && report.errors == 2)
    }

    @Test func namesWithLineBreaksSurviveTheirOwnChecksumFile() throws {
        let name = "two\nlines.txt"
        try box.file(name, "payload")
        let digest = try [UInt8](Insecure_MD5.of(Data(contentsOf: box.url(name))))
        let data = ChecksumFile.contents([(name, digest)], method: .md5, unixFormat: true, byteOrderMark: false)
        let text = String(decoding: data, as: UTF8.self)
        #expect(text.hasPrefix("\\") && text.split(separator: "\n").count == 1)
        #expect(ChecksumFile.parse(text, fileName: "x.md5").map(\.name) == [name])
        try data.write(to: box.url("x.md5"))
        #expect(try ChecksumRun.verify(checksumFiles: [item("x.md5")], run: run()).count(.ok) == 1)
        // An SFV file cannot hold such a name, and says so instead of writing a broken file.
        #expect(throws: ToolError.self) {
            try ChecksumRun.create(
                for: [item(name)], target: box.url("out.sfv"),
                options: {
                    var o = ChecksumRun.CreateOptions()
                    o.method = .crc32
                    return o
                }(),
                run: run())
        }
        #expect(!box.exists("out.sfv"))
    }

    @Test func checksumFileTooLargeForTheLimitIsAnErrorNotAShortenedText() throws {
        try box.file("big.md5", String(repeating: "x", count: 5_000))
        #expect(throws: ToolError.self) { try run().contents(of: box.url("big.md5"), limit: 1_000) }
        #expect(try run().contents(of: box.url("big.md5"), limit: 5_000).count == 5_000)
    }

    // MARK: Decode

    func decodeFile(_ name: String, _ bytes: [UInt8], into folder: String = "out") throws -> Decoder.Outcome {
        try box.folder(folder)
        try Data(bytes).write(to: box.url(name))
        return try Decoder.decodeChecked(item(name), into: box.url(folder), run: run())
    }

    @Test func urlSafeBase64WithLeadingDashesIsNotCutOff() throws {
        // 0xFB 0xEF 0xBE is "----" in the URL-safe alphabet.
        let line = "----"
        let text = (0..<40).map { _ in line }.joined(separator: "\n") + "\n"
        let outcome = try decodeFile("dashes.b64", Array(text.utf8))
        #expect(outcome.problems.isEmpty && outcome.files.count == 1)
        let expected = Data((0..<40).flatMap { _ in [UInt8]([0xFB, 0xEF, 0xBE]) })
        #expect(try Data(contentsOf: outcome.files[0]) == expected)
        // A boundary of a mail is still a boundary.
        let mail = "MIME-Version: 1.0\r\nContent-Transfer-Encoding: base64\r\n\r\nZm9vYmFy\r\n--boundary\r\n"
        let mailOutcome = try decodeFile("mail.eml", Array(mail.utf8), into: "out2")
        #expect(try Data(contentsOf: mailOutcome.files[0]) == Data("foobar".utf8))
    }

    @Test func unpaddedNumberedNeighboursAreNotGluedTogether() throws {
        try box.folder("out")
        try "Zm9vYmFy".write(to: box.url("photo1.b64"), atomically: true, encoding: .utf8)
        try "YmF6cXV4".write(to: box.url("photo2.b64"), atomically: true, encoding: .utf8)
        let outcome = try Decoder.decodeChecked(item("photo1.b64"), into: box.url("out"), run: run())
        #expect(try Data(contentsOf: outcome.files[0]) == Data("foobar".utf8))
        #expect(names("out") == ["photo1"])
    }

    @Test func partsWrittenByTheEncoderStillJoin() throws {
        let content = Data((0..<5_000).map { UInt8(truncatingIfNeeded: $0 &* 7) })
        try content.write(to: box.url("data.bin"))
        try box.folder("enc")
        try box.folder("dec")
        let written = try Encoder.encode(
            item("data.bin"), into: box.url("enc"), method: .mime, linesPerFile: 20, run: run())
        #expect(written.count > 1)
        let outcome = try Decoder.decodeChecked(registry.item(at: written[0])!, into: box.url("dec"), run: run())
        #expect(outcome.problems.isEmpty)
        #expect(try Data(contentsOf: outcome.files[0]) == content)
    }

    func encodeUU(_ content: Data, xx: Bool = false) throws -> String {
        try content.write(to: box.url("src.bin"))
        try box.folder("enc")
        let written = try Encoder.encode(item("src.bin"), into: box.url("enc"), method: xx ? .xxe : .uue, run: run())
        return String(decoding: try Data(contentsOf: written[0]), as: UTF8.self)
    }

    @Test func uuencodeThatIsIncompleteOrDamagedIsReported() throws {
        let content = Data((0..<450).map { UInt8(truncatingIfNeeded: $0 &* 13 &+ 5) })
        let good = try encodeUU(content)
        let ok = try decodeFile("good.uue", Array(good.utf8))
        let okData = try Data(contentsOf: ok.files[0])
        #expect(ok.problems.isEmpty && okData == content)

        var lines = good.components(separatedBy: "\r\n")
        // Missing end (and everything after): the last part is missing.
        let cut = lines.firstIndex(of: "end")!
        let noEnd = lines[..<cut].joined(separator: "\r\n") + "\r\n"
        let incomplete = try decodeFile("noend.uue", Array(noEnd.utf8), into: "o2")
        #expect(incomplete.problems.count == 1 && incomplete.problems[0].contains("end"))
        #expect(incomplete.files.count == 1)

        // A line dropped from the middle: the size at the end does not agree.
        lines.remove(at: 4)
        let dropped = try decodeFile("dropped.uue", Array(lines.joined(separator: "\r\n").utf8), into: "o3")
        #expect(dropped.problems.count == 1 && dropped.problems[0].contains("405 bytes"))

        // A damaged line (a character that is not in the alphabet).
        var damaged = good.components(separatedBy: "\r\n")
        damaged[3] = String(damaged[3].dropLast(10)) + "~~~~~~~~~~"
        let bad = try decodeFile("bad.uue", Array(damaged.joined(separator: "\r\n").utf8), into: "o4")
        #expect(!bad.problems.isEmpty)
    }

    func yenc(_ content: [UInt8], size: Int? = nil, crc: UInt32? = nil) -> [UInt8] {
        var body: [UInt8] = []
        for byte in content {
            let encoded = byte &+ 42
            if encoded == 0 || encoded == 10 || encoded == 13 || encoded == 61 {
                body += [61, encoded &+ 64]
            } else {
                body.append(encoded)
            }
        }
        let hasher = CRC32Hasher()
        hasher.update(Data(content))
        let header = Array("=ybegin line=128 size=\(content.count) name=f.bin\r\n".utf8)
        let footer = Array(
            "\r\n=yend size=\(size ?? content.count) crc32=\(String(format: "%08x", crc ?? hasher.checksum))\r\n".utf8)
        return header + body + footer
    }

    @Test func yencSizeAndCRCAreChecked() throws {
        let content = (0..<300).map { UInt8(truncatingIfNeeded: $0 &* 31) }
        let good = try decodeFile("good.yenc", yenc(content))
        let goodData = try Data(contentsOf: good.files[0])
        #expect(good.problems.isEmpty && goodData == Data(content))
        let wrongSize = try decodeFile("size.yenc", yenc(content, size: 999_999), into: "o2")
        #expect(wrongSize.problems.contains { $0.contains("=yend says") })
        let wrongCRC = try decodeFile("crc.yenc", yenc(content, crc: 0xDEAD_BEEF), into: "o3")
        #expect(wrongCRC.problems.contains { $0.contains("CRC32") })
        let truncated = try decodeFile("cut.yenc", Array(yenc(content).prefix(60)), into: "o4")
        #expect(truncated.problems.contains { $0.contains("=yend") })
    }

    @Test func namesFromEncodedTextStayInsideTheTargetFolder() throws {
        // A slash followed by a combining mark is one character to Swift and a slash to the disk.
        let name = "../\u{301}pwn.txt"
        #expect(Decoder.safeName(name)?.utf8.contains(0x2F) == false)
        #expect(Decoder.safeName("a/b\\c/..") == nil)
        #expect(Decoder.safeName("..\u{301}") == "..\u{301}")
        let uue = "begin 644 \(name)\n#<'=N\n`\nend\n"
        try box.folder("target/inner")
        try Data(uue.utf8).write(to: box.url("evil.uue"))
        let outcome = try Decoder.decodeChecked(item("evil.uue"), into: box.url("target/inner"), run: run())
        #expect(
            outcome.files.count == 1
                && outcome.files[0].deletingLastPathComponent().path == box.url("target/inner").path)
        #expect(names("target") == ["inner"])

        // The same for the name a .crc file gives to the combined file.
        #expect(Combiner.storedName("../\u{301}pwn.txt")?.utf8.contains(0x2F) == false)
        #expect(Combiner.storedName("..") == nil && Combiner.storedName("") == nil)
    }

    // MARK: Nothing that was there before is lost

    @Test func cancelAfterOverwriteLeavesSplitPartsAsTheyWere() throws {
        try Data(repeating: 7, count: 3_000).write(to: box.url("data.bin"))
        try box.file("out/data.001", "old one")
        try box.file("out/data.002", "old two")
        try box.file("out/data.crc", "old crc")
        // The second question comes while the first new part is already being written.
        let cancel = CancellationFlag()
        #expect(throws: ToolError.cancelled) {
            try Splitter.split(
                item("data.bin"), into: box.url("out"), partSize: 1_000, run: run(cancel: cancel, cancelOnAsk: 2))
        }
        #expect(
            box.read("out/data.001") == "old one" && box.read("out/data.002") == "old two"
                && box.read("out/data.crc") == "old crc")
        #expect(names("out") == ["data.001", "data.002", "data.crc"])
        // Without the cancel they are replaced, all together.
        _ = try Splitter.split(item("data.bin"), into: box.url("out"), partSize: 1_000, run: run())
        let firstPart = try Data(contentsOf: box.url("out/data.001"))
        let thirdPart = try Data(contentsOf: box.url("out/data.003"))
        #expect(firstPart.count == 1_000 && thirdPart.count == 1_000)
        #expect(names("out") == ["data.001", "data.002", "data.003", "data.crc"])
    }

    @Test func cancelAfterOverwriteLeavesEncodedFileAsItWas() throws {
        try Data(repeating: 1, count: 5_000).write(to: box.url("data.bin"))
        try box.file("out/data.b64", "old")
        let cancel = CancellationFlag()
        #expect(throws: ToolError.cancelled) {
            try Encoder.encode(
                item("data.bin"), into: box.url("out"), method: .mime, run: run(cancel: cancel, cancelOnAsk: 1))
        }
        #expect(box.read("out/data.b64") == "old" && names("out") == ["data.b64"])
    }

    @Test func cancelAfterOverwriteLeavesCombinedFileAndPartsAsTheyWere() throws {
        try box.file("in/f.001", "aaa")
        try box.file("in/f.002", "bbb")
        try box.file("out/f", "old combined")
        let cancel = CancellationFlag()
        let parts = [try item("in/f.001"), try item("in/f.002")]
        #expect(throws: ToolError.cancelled) {
            try Combiner.combine(parts, info: nil, into: box.url("out"), run: run(cancel: cancel, cancelOnAsk: 1))
        }
        #expect(box.read("out/f") == "old combined" && box.read("in/f.001") == "aaa" && names("out") == ["f"])
        let outcome = try Combiner.combine(parts, info: nil, into: box.url("out"), run: run())
        #expect(outcome.parts == 2 && box.read("out/f") == "aaabbb")
    }

    @Test func decodeCancelledAfterOverwriteKeepsTheOldFile() throws {
        try box.file("out/f", "old")
        try Data("begin 644 f\n#86)C\n`\nend\n".utf8).write(to: box.url("f.uue"))
        let cancel = CancellationFlag()
        #expect(throws: ToolError.cancelled) {
            try Decoder.decode(item("f.uue"), into: box.url("out"), run: run(cancel: cancel, cancelOnAsk: 1))
        }
        #expect(box.read("out/f") == "old" && names("out") == ["f"])
    }

    @Test func sameFileGuardSeesCaseVariantsAndLinks() throws {
        try box.file("real/X.crc", "x")
        try FileManager.default.createSymbolicLink(at: box.url("alias"), withDestinationURL: box.url("real"))
        #expect(ToolRun.isSameFile(box.url("alias/X.crc"), box.url("real/X.crc")))
        #expect(
            ToolRun.isSameFile(box.url("real/x.CRC"), box.url("real/X.crc"))
                == (FileManager.default.fileExists(atPath: box.url("real/x.CRC").path)))
        #expect(!ToolRun.isSameFile(box.url("real/other"), box.url("real/X.crc")))
        // Splitting a part of its own series in place is refused through a link as well.
        try box.file("real/data.001", "abc")
        #expect(throws: ToolError.self) {
            try Splitter.split(item("real/data.001"), into: box.url("alias"), partSize: 10, run: run())
        }
        #expect(box.read("real/data.001") == "abc")
    }

    @Test func aHugeLinesPerFileDoesNotTrap() throws {
        try Data(repeating: 3, count: 500).write(to: box.url("data.bin"))
        try box.folder("out")
        let written = try Encoder.encode(
            item("data.bin"), into: box.url("out"), method: .uue, linesPerFile: 999_999_999_999_999_999, run: run())
        #expect(written.count == 1)
    }

    @Test func everyThreadWaitsWhilePausedInAReport() {
        // While one thread's report is held (a paused job), the others that report queue up behind it.
        let held = DispatchSemaphore(value: 0)
        let entered = DispatchSemaphore(value: 0)
        let reports = ReportCounter()
        let run = ToolRun(
            fileSystems: registry,
            report: { _ in
                if reports.add() == 1 {
                    entered.signal()
                    held.wait()
                }
            })
        let first = Thread { run.advance(10, force: true) }
        first.start()
        entered.wait()
        let finished = ReportCounter()
        let group = DispatchGroup()
        for _ in 0..<3 {
            group.enter()
            DispatchQueue.global().async {
                Thread.sleep(forTimeInterval: 0.08)
                run.advance(1)
                _ = finished.add()
                group.leave()
            }
        }
        // They have had time to arrive; none has got past the held report (a miss here can only be a slow machine).
        Thread.sleep(forTimeInterval: 0.4)
        #expect(finished.value == 0)
        held.signal()
        group.wait()
        #expect(finished.value == 3)
    }
}

private final class ReportCounter: @unchecked Sendable {
    private let lock = NSLock()
    private var count = 0
    func add() -> Int {
        lock.lock()
        defer { lock.unlock() }
        count += 1
        return count
    }
    var value: Int {
        lock.lock()
        defer { lock.unlock() }
        return count
    }
}

private enum Insecure_MD5 {
    static func of(_ data: Data) -> [UInt8] {
        let hasher = ChecksumMethod.md5.makeHasher()
        hasher.update(data)
        return hasher.finish()
    }
}
