import AFMKernel
import Foundation
import LocalFileSystemPlugin
import TestSupport
import Testing

@testable import FileToolsPlugin

/// Review round 2: checksum files that must not be misread, Decode that must say what is
/// missing, and the tools that must never touch what was there before.
@Suite
internal struct Review2FileTools {
    /// Counts the reports of a run, from any thread.
    ///
    /// Unchecked `Sendable`: `count` is guarded by `lock`.
    private final class ReportCounter: @unchecked Sendable {
        /// Guards `count`.
        private let lock = NSLock()
        /// The reports so far (under `lock`).
        private var count = 0

        /// The reports so far.
        var value: Int {
            lock.lock()
            defer { lock.unlock() }
            return count
        }

        /// Counts one more report and returns the count.
        func add() -> Int {
            lock.lock()
            defer { lock.unlock() }
            count += 1
            return count
        }

        deinit {
            // Nothing to release.
        }
    }

    /// The folders on disk.
    internal let box: Sandbox
    /// The file systems: the local one.
    internal let registry = FileSystemRegistry()

    /// A bench on a folder of its own.
    internal init() throws {
        box = try Sandbox()
        registry.register(LocalFileSystem())
    }

    /// The MD5 digest of `data`.
    private static func md5(_ data: Data) -> [UInt8] {
        let hasher = ChecksumMethod.md5.makeHasher()
        hasher.update(data)
        return hasher.finish()
    }

    /// The file at `path` of the box.
    internal func item(_ path: String) throws -> FileItem {
        try #require(registry.item(at: box.url(path)))
    }

    /// A run that overwrites what is in the way.
    internal func run() -> ToolRun {
        run(cancel: CancellationFlag(), cancelOnAsk: nil)
    }

    /// A run that overwrites what is in the way, and sets `cancel` when it asks for the `cancelOnAsk`th time.
    internal func run(cancel: CancellationFlag, cancelOnAsk: Int?) -> ToolRun {
        // Used by the callbacks, which run one at a time while the calls below wait for them.
        nonisolated(unsafe) var asked = 0
        return ToolRun(
            fileSystems: registry,
            cancellation: cancel,
            report: { _ in
                // Not watched here.
            },
            askExisting: { _ in
                asked += 1
                if asked == cancelOnAsk {
                    cancel.cancel()
                }
                return .overwrite
            }
        )
    }

    /// The names in `folder` of the box, sorted.
    internal func names(_ folder: String) -> [String] {
        ((try? FileManager.default.contentsOfDirectory(atPath: box.url(folder).path)) ?? []).sorted()
    }

    // MARK: Checksum files

    /// In an SFV file a name that starts like a comment is an entry, and is written so that it reads back as itself.
    @Test
    internal func sfvNamesThatLookLikeCommentsAreEntries() {
        let text =
            "; Generated by WIN-SFV32 v1.1a on 12/10/2005 at 09:07.46\n#notes.txt 1A2B3C4D\n;x.txt 00000001\n"
            + "ok.txt 0000000F\n"
        let entries = ChecksumFile.parse(text, fileName: "set.sfv")
        #expect(entries.map(\.name) == ["#notes.txt", ";x.txt", "ok.txt"])
        // Written so that it reads back as itself.
        let line = ChecksumFile.line(name: ";x.txt", digest: [0, 0, 0, 1], method: .crc32)
        #expect(line == "./;x.txt 00000001")
        #expect(ChecksumFile.parse(line, fileName: "set.sfv").map(\.name) == ["./;x.txt"])
        // In the other formats a line that starts with # or ; is a comment.
        #expect(ChecksumFile.parse("# a comment 1A2B3C4D\n", fileName: "set.md5").isEmpty)
    }

    /// The lines of a checksum file that are neither an entry nor a comment are counted.
    @Test
    internal func linesThatCannotBeReadAreCounted() {
        let text =
            "d41d8cd98f00b204e9800998ecf8427 *short.txt\n\nd41d8cd98f00b204e9800998ecf8427e *\n"
            + "d41d8cd98f00b204e9800998ecf8427e *fine.txt\njunk\n"
        let parsed = ChecksumFile.parseLines(text, fileName: "x.md5")
        #expect(parsed.entries.map(\.name) == ["fine.txt"])
        #expect(parsed.unreadableLines == [1, 3, 5])
        #expect(ChecksumFile.parseLines("", fileName: "x.md5").unreadableLines.isEmpty)
    }

    /// An empty or unreadable checksum file, and every line that cannot be read, is an error of Verify.
    @Test
    internal func emptyAndUnreadableChecksumFilesAreErrors() throws {
        try box.file("empty.md5", "")
        try box.file("junk.sha256", "this is prose, not checksums\nsecond line\n")
        try box.file("short.md5", "d41d8cd98f00b204e9800998ecf8427 *a.txt\n")
        try box.file("a.txt", "alpha")
        let files = try ["empty.md5", "junk.sha256", "short.md5"].map(item)
        let report = try ChecksumRun.verify(checksumFiles: files, run: run())
        #expect(report.errors == 1 + 2 + 1)
        #expect(report.count(.unreadable) == 4 && report.count(.correct) == 0)
        #expect(report.text(onlyErrors: true).contains("Cannot read any checksum"))
        #expect(report.text(onlyErrors: true).contains("Cannot read line 2!"))
        #expect(report.failedNames.contains("empty.md5"))
    }

    /// Files whose names look like SFV comments are verified, and found when damaged.
    @Test
    internal func sfvEntriesWithCommentLikeNamesAreVerified() throws {
        try box.file("#notes.txt", "one")
        try box.file(";x.txt", "two")
        try box.file("ok.txt", "three")
        let entries = try ["#notes.txt", ";x.txt", "ok.txt"]
            .map { name -> (name: String, digest: [UInt8]) in
                let hasher = CRC32Hasher()
                hasher.update(try Data(contentsOf: box.url(name)))
                return (name, hasher.finish())
            }
        let data = ChecksumFile.contents(entries, method: .crc32, unixFormat: true, byteOrderMark: false)
        try data.write(to: box.url("set.sfv"))
        #expect(try ChecksumRun.verify(checksumFiles: [item("set.sfv")], run: run()).count(.correct) == 3)
        // Damaged, both are caught.
        try "changed".write(to: box.url("#notes.txt"), atomically: true, encoding: .utf8)
        try "changed".write(to: box.url(";x.txt"), atomically: true, encoding: .utf8)
        let report = try ChecksumRun.verify(checksumFiles: [item("set.sfv")], run: run())
        #expect(report.count(.wrongChecksum) == 2 && report.count(.correct) == 1 && report.errors == 2)
    }

    /// A name with a line break is escaped in a GNU checksum file and read back; an SFV file refuses it.
    @Test
    internal func namesWithLineBreaksSurviveTheirOwnChecksumFile() throws {
        let name = "two\nlines.txt"
        try box.file(name, "payload")
        let digest = Self.md5(try Data(contentsOf: box.url(name)))
        let data = ChecksumFile.contents([(name, digest)], method: .md5, unixFormat: true, byteOrderMark: false)
        let text = String(bytes: data, encoding: .utf8) ?? ""
        #expect(text.hasPrefix("\\") && text.split(separator: "\n").count == 1)
        #expect(ChecksumFile.parse(text, fileName: "x.md5").map(\.name) == [name])
        try data.write(to: box.url("x.md5"))
        #expect(try ChecksumRun.verify(checksumFiles: [item("x.md5")], run: run()).count(.correct) == 1)
        // An SFV file cannot hold such a name, and says so instead of writing a broken file.
        #expect(throws: ToolError.self) {
            try ChecksumRun.create(
                for: [item(name)],
                target: box.url("out.sfv"),
                options: ChecksumRun.CreateOptions(),
                run: run()
            )
        }
        #expect(!box.exists("out.sfv"))
    }

    /// A checksum file larger than the limit is an error, never a shortened text.
    @Test
    internal func checksumFileTooLargeForTheLimitIsAnErrorNotAShortenedText() throws {
        try box.file("big.md5", String(repeating: "x", count: 5_000))
        #expect(throws: ToolError.self) { try run().contents(of: box.url("big.md5"), limit: 1_000) }
        #expect(try run().contents(of: box.url("big.md5"), limit: 5_000).count == 5_000)
    }

    /// While one thread's report is held (a paused job), the others that report wait behind it.
    @Test
    internal func everyThreadWaitsWhilePausedInAReport() {
        // While one thread's report is held (a paused job), the others that report queue up behind it.
        let held = DispatchSemaphore(value: 0)
        let entered = DispatchSemaphore(value: 0)
        let reports = ReportCounter()
        let run = ToolRun(
            fileSystems: registry,
            cancellation: CancellationFlag(),
            report: { _ in
                if reports.add() == 1 {
                    entered.signal()
                    held.wait()
                }
            },
            askExisting: { _ in .overwrite }
        )
        let first = Thread { run.advance(10, items: 0, force: true) }
        first.start()
        entered.wait()
        let finished = ReportCounter()
        let group = DispatchGroup()
        for _ in 0..<3 {
            group.enter()
            // Each one's report is due (forced): a report that is not due does not wait for the turn, and whether
            // one is due by the clock depended on how far apart the system started the threads.
            OtherThread.start {
                run.advance(1, items: 0, force: true)
                _ = finished.add()
                group.leave()
            }
        }
        // They have had time to arrive; none has got past the held report (a miss here can only be a slow machine).
        Thread.sleep(forTimeInterval: 0.4)
        #expect(finished.value == 0)
        held.signal()
        group.wait()
        #expect(finished.value == 3)
    }
}
