#!/bin/bash
# build.sh rel|asan [product...]     builds the fuzz drivers against the project's sources.
#   rel   plain -O                          -> out/build-rel/release/fuzz-<group>
#   asan  -O, AddressSanitizer, edge counters -> out/build-asan/release/fuzz-<group>
# Without a product, all seven groups are built. FUZZ_JOBS sets the number of compile jobs.
HERE=$(cd "$(dirname "$0")" && pwd)
kind=${1:-rel}; shift
[ $# -eq 0 ] && set -- fuzz-arch fuzz-net fuzz-tools fuzz-kernel fuzz-misc fuzz-viewer fuzz-diff
mkdir -p "$HERE/out"
# The slow reference of the HTML-to-text conversion is the project's own (a test file): taken over
# before every build, without its `import Testing`, so that it cannot fall behind the product.
reference="$HERE/../PluginTests/ViewerAdoptHTMLReference.swift"
if [ -f "$reference" ]; then
  { echo "// Generated by build.sh from Tests/PluginTests/ViewerAdoptHTMLReference.swift. Do not edit."; grep -v '^import Testing$' "$reference"; } > "$HERE/out/HTMLReference.swift.new"
  cmp -s "$HERE/out/HTMLReference.swift.new" "$HERE/pkg/Fuzz/fuzz-viewer/HTMLReference.swift" || cp "$HERE/out/HTMLReference.swift.new" "$HERE/pkg/Fuzz/fuzz-viewer/HTMLReference.swift"
  rm -f "$HERE/out/HTMLReference.swift.new"
fi
cd "$HERE/pkg" || exit 1
case $kind in
  asan) flags=(--scratch-path "$HERE/out/build-asan" -c release --sanitize=address -Xswiftc -sanitize-coverage=edge,inline-8bit-counters) ;;
  rel)  flags=(--scratch-path "$HERE/out/build-rel" -c release) ;;
  *) echo "usage: build.sh rel|asan [product...]" >&2; exit 2 ;;
esac
status=0
for product in "$@"; do
  swift build "${flags[@]}" -Xswiftc -enable-testing -Xswiftc -g -j "${FUZZ_JOBS:-6}" --product "$product" > "$HERE/out/build-$kind-$product.log" 2>&1
  code=$?
  if [ $code -ne 0 ]; then
    status=$code
    echo "BUILD FAILED $kind $product (full log: out/build-$kind-$product.log)"
    grep -E "error:" "$HERE/out/build-$kind-$product.log" | sort -u | cut -c1-400 | head -60
  else
    echo "built $kind $product"
  fi
done
exit $status
